RULES_FILE=/etc/udev/rules.d/70-xrhardware.rules
# Installed rules that cover the PS VR2 (054c:0cde) and both Sense controllers (054c:0e45 left, 0e46 right).
rules_cover_psvr2() {
	local f
	for f in /etc/udev/rules.d/*.rules /run/udev/rules.d/*.rules /usr/lib/udev/rules.d/*.rules /lib/udev/rules.d/*.rules; do
		[ -r "$f" ] || continue
		grep -qi '054c' "$f" && grep -qi '0cde' "$f" && grep -qi '0e45' "$f" && grep -qi '0e46' "$f" && { echo "$f"; return 0; }
	done
	return 1
}
RULES_HAVE="$(rules_cover_psvr2 || true)"
RULES_NEEDED=0
[ -z "$RULES_HAVE" ] && RULES_NEEDED=1
