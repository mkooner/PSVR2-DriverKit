"""Fit the custom gesture mapping (open / pinch / fist / point / claw) on a labelled benchmark and write it as a C
header for Mercury (hg_custom_gesture_weights.h). Same features and classifier as gesture_map.py's "embedding +
joints" reader (scores are per-frame softmax logits; the driver averages the last 10 frames). One model per hand, fitted
on every gesture prompt of the benchmark (gesture_map.py gives the held-out scores).
usage: gesture_train.py detection.log gesture-labels.csv replay_to_session_ns out.h"""
import sys, os
import numpy as np
sys.argv = sys.argv[:4] + sys.argv[5:]  # gesture_map's arguments
out_path = os.environ['GESTURE_HEADER']
os.environ['KINDS'] = ''  # don't run gesture_map's evaluation
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gesture_map.py')).read()
src = src.split("SMOOTH = int(")[0]  # data loading, features and fit() only
g = {}
exec(compile(src, 'gesture_map.py', 'exec'), g)
prompts, frames, vec, CLASSES, np_ = g['prompts'], g['frames'], g['vec'], g['CLASSES'], g['np']
blocks = []
dims = None
for hand in (0, 1):
    X, y = [], []
    for p in prompts:
        if p['hand'] != hand:
            continue
        for fr in frames(p):
            X.append(vec(fr, 'both')); y.append(CLASSES.index(p['g']))
    X, y = np.array(X), np.array(y)
    mu, sd = X.mean(0), X.std(0) + 1e-6
    Xn = (X - mu) / sd
    k = len(CLASSES)
    W = np.zeros((X.shape[1], k)); bb = np.zeros(k); Y = np.eye(k)[y]
    cw = len(y) / (k * np.maximum(np.bincount(y, minlength=k), 1)); sw = cw[y][:, None]
    for _ in range(600):
        Z = Xn @ W + bb; Z -= Z.max(1, keepdims=True); P = np.exp(Z); P /= P.sum(1, keepdims=True)
        G = (P - Y) * sw / len(y)
        W -= 0.5 * (Xn.T @ G + 1e-2 * W); bb -= 0.5 * G.sum(0)
    acc = ((Xn @ W + bb).argmax(1) == y).mean()
    print(f"hand {hand}: {len(y)} frames, {X.shape[1]} features, fitted-frame accuracy {acc:.2f} (in-sample)", file=sys.stderr)
    dims = X.shape[1]
    lit = lambda v: (lambda t: t if any(c in t for c in '.en') else t + '.0')(f'{v:.7g}') + 'f'
    f = lambda a: ', '.join(lit(v) for v in a)
    blocks.append(f"\t{{\n\t    {{{f(mu)}}},\n\t    {{{f(sd)}}},\n\t    {{{f(W.T.reshape(-1))}}},\n\t    {{{f(bb)}}},\n\t}},")
with open(out_path, 'w') as o:
    o.write(f"""// Copyright 2026, Mehrab Kooner
// SPDX-License-Identifier: BSL-1.0
/*!
 * @file
 * @brief Custom gesture mapping for PS VR2 camera images (generated by psvr2-test hands/gesture_train.py; don't edit).
 *
 * A softmax classifier per hand (0 left, 1 right) over: each camera's MediaPipe gesture embedding (128, view 0 then 1,
 * zeros when the camera has no reading), two "camera has a reading" flags, then each camera's 18 joint measures (thumb
 * tip to each fingertip and each fingertip to the wrist, per finger, / palm width; the cosine of the bend at 10 finger
 * joints) and the two flags again. Classes: open, pinch, fist, point, claw. Fitted on the 2026-11-25 16:46 benchmark;
 * held-out scores (fit one round of prompts, test the other) in the commit message.
 */
#pragma once

#define HG_CUSTOM_GESTURE_FEATURES {dims}
#define HG_CUSTOM_GESTURE_CLASSES {len(CLASSES)}

struct hg_custom_gesture_model
{{
	float mean[HG_CUSTOM_GESTURE_FEATURES];
	float scale[HG_CUSTOM_GESTURE_FEATURES];
	float weight[HG_CUSTOM_GESTURE_CLASSES * HG_CUSTOM_GESTURE_FEATURES]; //!< class-major
	float bias[HG_CUSTOM_GESTURE_CLASSES];
}};

static const struct hg_custom_gesture_model hg_custom_gesture_models[2] = {{
""" + '\n'.join(blocks) + "\n};\n")
print("wrote", out_path, file=sys.stderr)
