struct xrt_tracking_sinks;

/*!
 * Controlling the frame capture parameters
 *
 * Used to configure cameras. since there is no guarantee every
 * data source will support any/all of these params, a 'best effort'
 * should be made to apply them. all numeric values are normalised
 * floats for broad applicability.
 *
 * @ingroup xrt_iface
 * @see xrt_ds
 */
struct xrt_ds_frame_capture_parameters
{
	float gain;
	float exposure;
};

/*!
 * @see xrt_ds
 * @ingroup xrt_iface
 */
struct xrt_ds_frame_mode
{
	uint32_t width;
	uint32_t height;
	enum xrt_format format;
	enum xrt_stereo_format stereo_format;
};

/*!
 * Enum describing which type of capture we are doing.
 * @see xrt_ds
 * @ingroup xrt_iface
 */
enum xrt_ds_capture_type
{
	XRT_DS_CAPTURE_TYPE_TRACKING = 0,
	XRT_DS_CAPTURE_TYPE_CALIBRATION = 1,
};

/*!
 * Structure describing a data source's tracking streaming capabilities.
 * @see xrt_ds
 * @ingroup xrt_iface
 */
struct xrt_ds_tracking_capabilities
{
	//! The number of cameras that are capable of streaming. See @ref XRT_TRACKING_MAX_CAMS
	uint32_t cam_count;
	//! The number of IMUs that are capable of streaming. See @ref XRT_TRACKING_MAX_IMUS.
	uint32_t imu_count;
};

/*!
 * @interface xrt_ds
 * Generic data source intended for tracking purposes, currently primarily produces video frames.
 *
 * Multiple subframes (like stereo and mipmaps) can be generated by a single frame mode.
 *
 * @ingroup xrt_iface
 */
struct xrt_ds
{
	//! Name of the data source, comes from the implementation.
	char name[512];
	//! Data source product identifier, matches the prober device if applicable.
	char product[32];
	//! Data source manufacturer, matches the prober device if applicable.
	char manufacturer[32];
	//! Data source serial number, matches the prober device if applicable.
	char serial[32];

	/*!
	 * All data produced by this data source are tagged with this id.
	 */
	uint64_t source_id;

	/*!
	 * Enumerate all available modes that this data source supports.
	 *
	 * This *may* return no modes, which should be checked by the caller.
	 * In this case, the data source does not support streaming frames.
	 */
	xrt_result_t (*enumerate_frame_modes)(struct xrt_ds *xds,
	                                      struct xrt_ds_frame_mode **out_modes,
	                                      uint32_t *out_count);

	/*!
	 * Gets the capabilities of this data source, matching with the amount of sinks it's able to push to in
	 * frame_stream_start. This allows an optical tracker to build itself around a data source before starting a
	 * stream with all possible data (or with whatever subset it may need).
	 *
	 * @param      xds              The data source.
	 * @param[out] out_capabilities A pointer to write the capabilities into.
	 */
	xrt_result_t (*get_tracking_capabilities)(struct xrt_ds *xds,
	                                          struct xrt_ds_tracking_capabilities *out_capabilities);

	/*!
	 * Set the capture parameters, not all types of parameters may be supported on some capture devices.
	 *
	 * This function *must* not fail from a subset of requested parameters being unsupported!
	 */
	xrt_result_t (*configure_capture)(struct xrt_ds *xds, struct xrt_ds_frame_capture_parameters *cp);

	/*!
	 * Start a single frame capture stream.
	 *
	 * If you only need single frames (or direct stereo frames!),
	 * this is the easiest way to get that data out.
	 *
	 * @param xds              The data source.
	 * @param xs               The sink to push frames into.
	 * @param capture_type     The type of capture this is.
	 * @param frame_mode_index The mode the frame stream should start with.
	 */
	xrt_result_t (*frame_stream_start)(struct xrt_ds *xds,
	                                   struct xrt_frame_sink *xs,
	                                   enum xrt_ds_capture_type capture_type,
	                                   uint32_t frame_mode_index);

	/*!
	 * Sets up a multitude of tracking-related streams that this device may support.
	 * If this method is used instead of @ref frame_stream_start, stereo frames will instead usually be split and
	 * sent to individual sinks, instead of being sent as stereo frames to a single sink.
	 */
	xrt_result_t (*tracking_streams_start)(struct xrt_ds *xds, struct xrt_tracking_sinks *sinks);

	/*!
	 * Stop the capture stream.
	 */
	xrt_result_t (*stream_stop)(struct xrt_ds *xds);

	/*!
	 * Is the capture stream running.
	 */
	xrt_result_t (*is_running)(struct xrt_ds *xds, bool *out_is_running);
};


/*
 *
 * Inline functions.
 *
 */

/*!
 * @copydoc xrt_ds::enumerate_frame_modes
 *
 * Helper for calling through the function pointer.
 *
 * @public @memberof xrt_ds
 */
static inline xrt_result_t
xrt_ds_enumerate_frame_modes(struct xrt_ds *xds, struct xrt_ds_frame_mode **out_modes, uint32_t *out_count)
{
	return xds->enumerate_frame_modes(xds, out_modes, out_count);
}

/*!
 * @copydoc xrt_ds::get_tracking_capabilities
 *
 * Helper for calling through the function pointer.
 *
 * @public @memberof xrt_ds
 */
static inline xrt_result_t
xrt_ds_get_tracking_capabilities(struct xrt_ds *xds, struct xrt_ds_tracking_capabilities *out_capabilities)
{
	return xds->get_tracking_capabilities(xds, out_capabilities);
}

/*!
 * @copydoc xrt_ds::configure_capture
 *
 * Helper for calling through the function pointer.
 *
 * @public @memberof xrt_ds
 */
static inline xrt_result_t
xrt_ds_configure_capture(struct xrt_ds *xds, struct xrt_ds_frame_capture_parameters *cp)
{
	return xds->configure_capture(xds, cp);
}

/*!
 * @copydoc xrt_ds::frame_stream_start
 *
 * Helper for calling through the function pointer.
 *
 * @public @memberof xrt_ds
 */
static inline xrt_result_t
xrt_ds_frame_stream_start(struct xrt_ds *xds,
                          struct xrt_frame_sink *xs,
                          enum xrt_ds_capture_type capture_type,
                          uint32_t frame_mode_index)
{
	return xds->frame_stream_start(xds, xs, capture_type, frame_mode_index);
}

/*!
 * @copydoc xrt_ds::tracking_streams_start
 *
 * Helper for calling through the function pointer.
 *
 * @public @memberof xrt_ds
 */
static inline xrt_result_t
xrt_ds_tracking_streams_start(struct xrt_ds *xds, struct xrt_tracking_sinks *sinks)
{
	return xds->tracking_streams_start(xds, sinks);
}

/*!
 * @copydoc xrt_ds::stream_stop
 *
 * Helper for calling through the function pointer.
 *
 * @public @memberof xrt_ds
 */
static inline xrt_result_t
xrt_ds_stream_stop(struct xrt_ds *xds)
{
	return xds->stream_stop(xds);
}

/*!
 * @copydoc xrt_ds::is_running
 *
 * Helper for calling through the function pointer.
 *
 * @public @memberof xrt_ds
 */
static inline xrt_result_t
xrt_ds_is_running(struct xrt_ds *xds, bool *out_is_running)
{
	return xds->is_running(xds, out_is_running);
}


